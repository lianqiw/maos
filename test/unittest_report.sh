#!/bin/sh
#Generate the unit test status report from the results (*.trs and *.log) of the
#cmocka unit tests in TOP_BUILDDIR/test. Called by unittest_driver.sh after each
#test is run, and by make doc with --coverage to include code coverage.
#The report is written in the build folder, never in the source folder.
#Usage: unittest_report.sh TOP_SRCDIR TOP_BUILDDIR [--coverage]
top_srcdir="$1"
top_builddir="$2"
coverage="$3"
out="$top_builddir/docs/unittest_status.md"
mkdir -p "$top_builddir/docs" || exit 1
tmp="$out.tmp$$"

config="$top_builddir/config.h"
cfg(){
	sed -n "s/^#define $1 //p" "$config" 2>/dev/null | tr -d '"'
}
compiler=$(cfg COMPILER)
if [ "$(cfg USE_CPP)" = 1 ];then lang="C++" ;else lang="C" ;fi
if [ "$(cfg CPU_SINGLE)" = 1 ];then prec="single" ;else prec="double" ;fi
cuda=$(cfg USE_CUDA)
if [ -n "$cuda" ] && [ "$cuda" != 0 ];then cuda="CUDA $cuda" ;else cuda="no CUDA" ;fi
rev=$(git -C "$top_srcdir" describe --always --dirty 2>/dev/null || echo unknown)

cd "$top_builddir/test" || exit 1
#Per test case results from the cmocka output in each log file.
results=$(for trs in *.trs ;do
	[ -f "$trs" ] || continue
	prog=${trs%.trs}
	res=$(sed -n 's/^:test-result: //p' "$trs")
	#Each test case starts with [ RUN ] name and ends with [ OK ], [ FAILED ], or [ SKIPPED ] name.
	awk -v prog="$prog" -v res="$res" '
		function name(line){sub(/^\[[^]]*\] */, "", line); split(line, a, " "); return a[1]}
		/^\[ *RUN *\]/     {cur=name($0); next}
		/^\[ *OK *\]/      {if(cur!=""){print prog "|" cur "|PASS"; n++; cur=""}}
		/^\[ *FAILED *\]/  {if(cur!=""){print prog "|" cur "|FAIL"; n++; cur=""}}
		/^\[ *SKIPPED *\]/ {if(cur!=""){print prog "|" cur "|SKIP"; n++; cur=""}}
		END{
			if(cur!=""){print prog "|" cur "|ERROR"; n++} #crashed in the middle of a test
			if(!n) print prog "|(program)|" res
		}' "${prog}.log"
done)

nprog=$(ls *.trs 2>/dev/null | wc -l | tr -d ' ')
ncase=$(printf '%s\n' "$results" | grep -c '|')
npass=$(printf '%s\n' "$results" | grep -c '|PASS$')
nfail=$(printf '%s\n' "$results" | grep -c -E '\|(FAIL|ERROR)$')
nskip=$(printf '%s\n' "$results" | grep -c '|SKIP$')

{
	echo '\page page96_unittest Unit Test Status'
	echo
	echo "This page is generated by \`make doc\` (\`test/unittest_report.sh\`) from the results of \`make check\`."
	echo
	echo "- Updated: $(date '+%Y-%m-%d %H:%M:%S %Z')"
	echo "- Source revision: $rev"
	echo "- Build: $compiler, $lang, $prec precision, $cuda"
	if [ "$nprog" = 0 ];then
		echo "- Summary: no unit test results. Run \`make check\` (requires cmocka)."
	else
		echo "- Summary: $npass of $ncase test cases passed in $nprog programs ($nfail failed, $nskip skipped)."
	fi
	if [ "$coverage" = "--coverage" ];then
		echo
		echo '\section unittest_coverage Code Coverage'
		echo
		$SHELL "$top_srcdir/test/unittest_coverage.sh" "$top_srcdir" "$top_builddir"
	fi
	if [ "$nprog" != 0 ];then
		echo
		echo '\section unittest_results Test Results'
		echo
		echo '| Program | Test case | Result | Run at |'
		echo '|---------|-----------|--------|--------|'
		printf '%s\n' "$results" | while IFS='|' read -r prog name res ;do
			[ -n "$prog" ] || continue
			when=$(date -r "${prog}.log" '+%Y-%m-%d %H:%M' 2>/dev/null)
			echo "| \`$prog\` | \`$name\` | $res | $when |"
		done
	fi
	if [ "$nfail" != 0 ];then
		echo
		echo '\section unittest_failures Failures'
		echo
		for trs in *.trs ;do
			prog=${trs%.trs}
			if grep -q -E '^:test-result: (FAIL|ERROR)' "$trs" ;then
				echo "\`$prog\`:"
				echo '\verbatim'
				if grep -q -E '^\[ *(ERROR|LINE) *\]' "${prog}.log" ;then
					grep -E '^\[ *(ERROR|LINE|FAILED) *\]' "${prog}.log" | grep -v -E 'FAILED *\] [0-9]+ test' | awk '!seen[$0]++' | head -40
				else
					tail -n 20 "${prog}.log"
				fi
				echo '\endverbatim'
				echo
			fi
		done
	fi
} > "$tmp" && mv "$tmp" "$out"

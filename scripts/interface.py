class loc(Structure):
    '''To interface numpy.array with C loc_t (lib/loc.h).

    loc(arr) wraps arr of shape (2, n) (row 0: x, row 1: y coordinates in
    meter) as loc_t. The data is borrowed if it is C contiguous double,
    otherwise a converted copy is kept in the object. dx and dy are estimated
    as the median of the nonzero spacing between consecutive points.

    Raises:
        ValueError: if arr is not of shape (2, n).
    '''
    _fields_ = [
        ('id',   c_uint32),
        ('locx', c_void_p),
        ('nloc', c_long),
        ('two',  c_long), 
        ('header',c_void_p),
        ('dummy_fp',c_void_p),
        ('dummy_fft',c_void_p),
        ('dummy_mem',c_void_p),
        ('dummy_async',c_void_p),
        ('dummy_deinit',c_void_p),
        ('dummy_make_keywords',c_void_p), #up to here. follow cell memory layout.
        ('locy', c_void_p),
        ('locstat_t', c_void_p),
        ('map',  c_void_p),
        ('dx',   c_double),
        ('dy',   c_double),
        ('ht',   c_double),
        ('iac',  c_double),
        ('dratio',c_double),
        ('aoi',c_double),
        ('npad', c_int),
        ]
    def __init__(self, arr=None): #convert from numpy to C. Memory is borrowed
        self.id= 0x36402 #M_LOC64
        if arr is not None:
            arr=np.asarray(arr)
            if len(arr.shape)!=2 or arr.shape[0] !=2 :
                raise(ValueError(f'loc: array has to be of shape 2xn, got {arr.shape}'))
            else:
                if arr.flags['C']==False or arr.dtype!=np.double:
                    arr=np.ascontiguousarray(arr, dtype=np.double)
                self.arr=arr #keep a reference so that the memory is valid while the object is alive
                dlocx=np.abs(arr[0,1:]-arr[0,0:-1])
                dlocy=np.abs(arr[1,1:]-arr[1,0:-1])
                self.locx=arr[0,].ctypes.data_as(c_void_p)
                self.nloc=arr.shape[1]
                self.two=2;
                self.header=None
                self.dummy_fp=None
                self.dummy_fft=None
                self.dummy_mem=None
                self.dummy_async=None
                self.dummy_deinit=None
                self.dummy_make_keywords=None
                self.locy=arr[1,].ctypes.data_as(c_void_p)
                self.locstat_t=None
                self.map=None
                self.dx=np.median(dlocx[dlocx>0])
                self.dy=np.median(dlocy[dlocy>0])
                self.ht=0
                self.iac=0
                self.dratio=1
                self.aoi=0
                self.npad=1
                self.python=True
                #print(f'loc: locx={self.locx:x} locy={self.locy:x}')
                #print('loc: dx={0}, dy={1}'.format(self.dx, self.dy))
        #default initialization to zero
    def __array_finalize__(self, obj):
        if obj is None:
            return
        self.__dict__.update(getattr(obj, "__dict__", {}))
class csr(Structure):#CSR sparse matrix. We convert C CSC to Python CSR just like arrays as numpy is row order
    '''To interface scipy sparse arrays with C sparse array (dsp/ssp/csp/zsp).

    csr(arr, tid=0) wraps scipy sparse array arr (other formats than CSR are
    converted to CSR) as a C sparse matrix with 64 bit index. A python CSR of
    shape (m, n) is the C CSC of nx=n, ny=m, consistent with dense arrays. The
    data of a CSR array is borrowed; indices are copied to 64 bit. Integer and boolean data
    are converted to float64.

    Raises:
        TypeError: if the dtype is not supported or does not match tid.
    '''
    _fields_=[ #need to match C memory layout
        ('id', c_uint32),
        ('x', c_void_p),
        ('nx', c_long),
        ('ny', c_long),
        ('header',   c_char_p),
        ('dummy_fp', c_void_p),
        ('nzmax', c_long),
        ('p', c_void_p),
        ('i', c_void_p),
        ('nref', c_void_p),
    ]
    def __init__(self, arr=None, tid=0): #convert from numpy to C. Memory is borrowed
        if arr is None:
            self.id=spdtype2id.get(np.float64)
        elif sp.issparse(arr):
            if arr.dtype.kind in 'biu': #integer or boolean
                arr=arr.astype(np.float64)
            self.id=spdtype2id.get(arr.dtype.type, 0)
            if self.id==0:
                raise TypeError(f'csr: unsupported data type {arr.dtype}')
            if  tid !=0 and tid !=0x6421 and self.id != tid:
                raise(TypeError(f'csr: data mismatch want {tid:#x}, got {self.id:#x}'))
            if arr.format!='csr':
                #Convert csc and other formats to csr. Using csc data directly
                #would give the transpose of the csr convention below.
                arr=arr.tocsr()
            if arr.format=='csr':
                self.ny, self.nx=arr.shape #python csr is maos csc transposed
            #save subarrays to avoid being GC'ed.
            self.xp=arr.data
            self.ip=arr.indices.astype(np_long) #np.long was removed from numpy
            self.pp=arr.indptr.astype(np_long) #p
            self.x=self.xp.ctypes.data_as(c_void_p) #data
            self.i=self.ip.ctypes.data_as(c_void_p) #row index
            self.p=self.pp.ctypes.data_as(c_void_p)
            self.nzmax=self.pp[-1]
            self.python=True
        else:
            raise(TypeError(f'csr: invalid conversion from {type(arr)}'))
    def __array_finalize__(self, obj):
        if obj is None:
            return
        self.__dict__.update(getattr(obj, "__dict__", {}))
def convert_fields(fields):
    '''Convert a dict of {field name: C type string} to a ctypes _fields_ list.

    Pointers to mat/cell types become POINTER(cell), loc_t* becomes
    POINTER(loc), other pointers c_void_p. Returns None if any field has an
    unsupported type (e.g., pointer to pointer, char, or function pointer).
    '''
    val2type={
        '*':c_void_p,
        'double':c_double,
        'real':c_double,
        'float':c_float,
        'long':c_long,
        'int':c_int,
    }
    newfields=[]
    for key,val in fields.items():
        if val[-1]=='*':
            if val[-2]=='*':
                print('Please handle pointer to pointer')
                return None
            if val.find('mat')!=-1 or val.find('cell')!=-1:
                val=POINTER(cell)
            elif val.find('loc_t')!=-1:
                val=POINTER(loc)
            else:
                val=c_void_p
        elif val in val2type:
            val=val2type[val]
        else:
            return None
        newfields.append((key,val))
    return newfields

def make_class(name, fields):
    '''Dynamically create a ctypes Structure class with the fields listed.

    Args:
        name: class name.
        fields: dict of {field name: C type string} in the C struct order.

    Returns:
        The class, or None if a field type is not supported (see convert_fields).
    '''
    fields_type=convert_fields(fields)
    if fields_type:
        return type(name, (Structure,), {"_fields_": fields_type})
    else:
        return None

type_map = {#python type to ctypes type
    int: c_int,
    float: c_double,
    bool: c_bool,
    bytes: c_char_p,
    str: c_char_p,
}
def dict_to_struct_type(data, name='struct'):
    '''Create a ctypes Structure class from a dictionary.

    Sparse arrays become POINTER(csr), numpy arrays POINTER(cell), and
    int/float/bool/bytes/str (and numpy scalars) the corresponding ctypes
    type. Fields with other types are skipped with a message.
    '''
    fields = []

    for k, v in data.items():
        #print(f'Field {k} has type {type(v)}')
        if isinstance(v, np.generic): #numpy scalar
            v=v.item()
        if sp.issparse(v):
            fields.append((k, POINTER(csr)))
        elif isinstance(v, np.ndarray):
            fields.append((k, POINTER(cell)))
        elif type(v) in type_map:
            fields.append((k, type_map[type(v)]))
        else:
            print(f'Unknown field {k} {type(v)}')
    
    struct=type(name, (Structure,), {"_fields_": fields})
    return struct
def dict_to_struct(data, struct=None, name='struct'):
    '''Convert a dictionary to a ctypes Structure instance.

    Args:
        data: dict of field values. Missing fields are zero (NULL).
        struct: Structure class (e.g., from make_class); created from data with
            dict_to_struct_type if None.
        name: class name when struct is None.

    Returns:
        The Structure instance. The converted arrays are kept in its _refs
        attribute, so they stay valid as long as the instance is alive.
    '''
    if struct is None:
        struct=dict_to_struct_type(data, name=name)

    values = {}
    refs = [] #keep the converted objects alive as long as the struct
    for k, vtype in struct._fields_: 
        v=data.get(k, None)
        if isinstance(v, np.generic): #numpy scalar
            v=v.item()
        if v is None:
            if vtype is c_void_p or issubclass(vtype, ctypes._Pointer):
                values[k]=None #NULL pointer
            continue #default value for other fields
        if issubclass(vtype, POINTER(loc)):
            obj=loc(v)
            refs.append(obj)
            values[k]=cast(pointer(obj), vtype)
        elif vtype is c_void_p and isinstance(v, np.ndarray) and v.dtype!=object:
            #pointer to numbers such as real*: pass the data
            if v.dtype!=np.double or not v.flags['C']:
                v=np.ascontiguousarray(v, dtype=np.double)
            refs.append(v)
            values[k]=v.ctypes.data_as(c_void_p)
        elif vtype is c_void_p or issubclass(vtype, ctypes._Pointer):
            obj=py2cell(v)
            if obj is None: #empty array
                values[k]=None
                continue
            if not isinstance(obj, Structure):
                raise TypeError(f'dict_to_struct: cannot convert field {k} of type {type(v)}')
            refs.append(obj)
            values[k]=cast(pointer(obj), vtype)
        else:
            values[k]=v.encode() if isinstance(v, str) else v

    res=struct(**values)
    res._refs=refs
    return res

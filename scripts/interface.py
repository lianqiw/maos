class cell_ndarray(np.ndarray):
    '''numpy.ndarray subclass created from a C array, carrying extra attributes.

    cell_ndarray(ctypes_pointer) copies the data pointed to by ctypes_pointer
    (a pointer to a C dense array or cell array) into a new numpy array. The C
    memory is not freed (ct2py does that). Sparse arrays are returned as
    scipy.sparse.csr_array instead. Cell arrays become object arrays of shape
    (ny, nx) ((nx,) if ny==1); NULL elements become empty arrays.

    Attributes:
        header: the keywords of the C array (string, may be empty).
        Each key=value entry of the header (separated by ; or newline) is also
            set as an attribute (key and value stripped of spaces; value as
            float if possible) unless the key clashes with an existing numpy
            array attribute. Keys such as sim.dt are accessed with getattr(arr, 'sim.dt').
    '''
    def __new__(cls, ctypes_pointer):#new creates new object
        #print(f'cell_ndarray __new__ {ctypes_pointer}')
        ctypes_array=cast(ctypes_pointer, POINTER(cell)).contents
        if ctypes_array.header:
            header=ctypes_array.header.decode('utf-8', errors='replace')
        else:
            header=''
        if not ctypes_array.p or ctypes_array.nx ==0 or ctypes_array.ny ==0:
            res=np.array([])
            kind=-1
        else:
            try:
                (tt, iscomplex, kind)=id2ctype.get(ctypes_array.id&0xFFFF)
            except TypeError:
                print(f"id2ctype: unknown type {ctypes_array.id:#x}")
                res=np.array([])
                kind=-1
        if kind==0 or kind==1: #dense matrix
            parr=cast(ctypes_array.p, POINTER(tt))
            if iscomplex:
                res=np.ctypeslib.as_array(parr, shape=(*ctypes_array.shape(),2)).copy()
                if tt is c_double:
                    res=np.squeeze(res.view(np.complex128), axis=-1)
                elif tt is c_float:
                    res=np.squeeze(res.view(np.complex64), axis=-1)
                else:
                    raise(Exception('Please implement'))
            else:
                res=np.ctypeslib.as_array(parr, shape=ctypes_array.shape()).copy()
        elif kind==2 or kind==3: #sparse matrix does not support subclassing like numpy
            return cell_csr_array(ctypes_pointer)
        elif kind==10: #cell array
            res=np.empty(ctypes_array.shape(1), dtype=object)
            parr=cast(ctypes_array.p, POINTER(c_void_p))
            for iy in range(ctypes_array.ny):
                for ix in range(ctypes_array.nx):
                    address=parr[ix+ctypes_array.nx*iy]
                    if address is not None:
                        pp=cast(address, POINTER(cell))
                        res[iy, ix]=cell_ndarray(pp) 
                    else:
                        res[iy, ix]=np.array([])
            if ctypes_array.ny==1:
                res=res[0,]

        obj=res.view(cls)
        obj.header=header
        if kind==1: #LOC
            ctypes_loc=cast(ctypes_pointer, POINTER(loc)).contents
            obj.dx=ctypes_loc.dx
            obj.dy=ctypes_loc.dy
            obj.ht=ctypes_loc.ht
            obj.iac=ctypes_loc.iac
        if len(header)>0:
            for pair in header.replace('\n',';').replace(';;',';').split(';'):
                if pair.find('=')>-1:
                    ires=pair.split('=')
                    if len(ires)==2:
                        key=ires[0].strip()
                        if not key or hasattr(np.ndarray, key):
                            continue #do not override array attributes such as shape or T
                        try:
                            setattr(obj, key, float(ires[1]))
                        except ValueError:
                            setattr(obj, key, ires[1].strip())
        return obj
    def __array_finalize__(self, obj): #this is called when res.view() is called
        if obj is None:
            return
        self.__dict__.update(getattr(obj, "__dict__", {}))
class cell_csr_array(sp.csr_array):
    '''Create scipy.sparse.csr_array from a C sparse array (copying the data).

    cell_csr_array(ctypes_pointer) returns a csr_array of shape (ny, nx) as the
    C sparse array (CSC of nx*ny) is the transpose of CSR. A dense C array is
    returned as cell_ndarray. The C memory is not freed.
    '''
    def __new__(cls, ctypes_pointer):
        #print(f'cell_csr_array __new__ {ctypes_pointer}')
        #create numpy object from C
        ctypes_array=cast(ctypes_pointer, POINTER(csr)).contents
        try:
            (tt, iscomplex, kind)=id2ctype.get(ctypes_array.id&0xFFFF)
        except TypeError:
            print(f"id2ctype: unknown type {ctypes_array.id:#x}")
            return None
        if kind==0 or kind==1:
            return cell_ndarray(ctypes_pointer)
        elif kind==2 or kind==3:
            if ctypes_array.nzmax>0:
                if iscomplex: #complex numbers stored as pairs of real numbers
                    xp=np.ctypeslib.as_array(cast(ctypes_array.x, POINTER(tt)), shape=(ctypes_array.nzmax,2))
                    xp=np.squeeze(xp.view(np.complex128 if tt is c_double else np.complex64), axis=-1)
                else:
                    xp=np.ctypeslib.as_array(cast(ctypes_array.x, POINTER(tt)), shape=(ctypes_array.nzmax,))
                if kind==2:
                    ip=np.ctypeslib.as_array(cast(ctypes_array.i, POINTER(c_long)), shape=(ctypes_array.nzmax,))
                    pp=np.ctypeslib.as_array(cast(ctypes_array.p, POINTER(c_long)), shape=(ctypes_array.ny+1,))
                elif kind==3:
                    ip=np.ctypeslib.as_array(cast(ctypes_array.i, POINTER(c_int)), shape=(ctypes_array.nzmax,))
                    pp=np.ctypeslib.as_array(cast(ctypes_array.p, POINTER(c_int)), shape=(ctypes_array.ny+1,))
                return sp.csr_array((xp, ip, pp), shape=(ctypes_array.ny, ctypes_array.nx), copy=True)
            else:
                return sp.csr_array((ctypes_array.ny,ctypes_array.nx))
        else:
            raise(TypeError(f"Unsupported CSR data kind: {kind}"))
    def __array_finalize__(self, obj):
        if obj is None:
            return
        self.__dict__.update(getattr(obj, "__dict__", {}))
            
def ct2py(var):
    '''Convert C data to Python data.

    Args:
        var: ctypes pointer to a MAOS array (as returned by C functions; the C
            memory is freed after conversion), a MAOS array struct (cell, csr;
            not freed), another ctypes Structure (converted to dict with each
            pointer field converted recursively), or a ctypes simple type.

    Returns:
        numpy array (cell_ndarray), scipy.sparse.csr_array, dict, or Python
        value. None for NULL pointers.
    '''
    if var is None:
        return None
    if isinstance(var, ctypes._Pointer):
        if not bool(var): #NULL pointer
            return None
        pointer=var
        var=pointer.contents
        owned=True #memory allocated by C. Free it after conversion.
    else:
        pointer=None
        owned=False
    if hasattr(var, 'id'): #a maos struct for array; conver to ndarray
        if pointer is None:
            pointer=ctypes.pointer(var)
        try:
            (tt, iscomplex, kind)=id2ctype.get(var.id&0xFFFF)
        except TypeError:
            print(f"id2ctype: unknown type {var.id:#x}")
            kind=-1
        if kind==-1:
            res=np.array([])
        elif kind==2 or kind==3:#sparse
            res=cell_csr_array(pointer)
        else:
            res=cell_ndarray(pointer)
        if owned:
            #print(f"Freeing {pointer}")
            lib.cellfree_do(cast(pointer, c_void_p))
    elif isinstance(var, Structure): #a generic struct; convert to dictionary
        result = {}
        for field_name, field_type in var._fields_:
            value = getattr(var, field_name)
            if isinstance(value, ctypes._Pointer):
                value=ct2py(value)
            elif field_type is c_void_p:
                print(f'unexpected: {field_name} is c_void_p')
                value = None
            result[field_name] = value
        res=result
    else:
        res=getattr(var, 'value', var) #ctypes simple type or already a Python value
    
    return res
class cell(Structure):
    '''To interface numpy.array with C cell (and dense matrix) types.

    cell(arr, tid=0) wraps numpy array arr as a C dmat/smat/cmat/zmat/lmat
    (numeric dtype) or cell (object dtype, converted recursively) with the
    same memory layout as the C struct (math/type.h). Numeric data is
    borrowed, not copied (unless a dtype conversion or C order copy is
    needed); a reference to the array is kept in the object. Arrays with more
    than 2 dimensions are converted to cell arrays (see arr2object); a 0-d
    array is treated as a vector of 1 element.

    Args:
        arr: numpy array, list, or None (empty cell).
        tid: expected MAOS type id (0 or 0x6421 for no conversion).

    Raises:
        TypeError: if the dtype is not supported or cannot be converted to tid.
    '''
    _fields_ = [ #fields compatible with C type of cell and mat
        ('id', c_uint32),
        ('p',  c_void_p),
        ('nx', c_long),
        ('ny', c_long),
        ('header', c_char_p),
        ('dummy_fp', c_void_p),
        ('dummy_fft', c_void_p),
        ('dummy_mem', c_void_p),
        ('dummy_async', c_void_p),
        ('dummy_deinit', c_void_p),
        ('dummy_make_keywords', c_void_p),
        ]
 
    def __init__(self, arr=None, tid=0):#convert from numpy to C. Memory is borrowed
        #attributes set within __init__ are per object
        #print(f'__init__ is called for cell {addressof(self)}')
        self.header=None
        self.dummy_fp=None
        self.dummy_fft=None
        self.dummy_mem=None
        self.dummy_async=None
        self.dummy_deinit=None
        self.dummy_make_keywords=None
        self.python=True
        if isinstance(arr, list):
            arr=np.asarray(arr)
        
        if arr is not None and arr.ndim>2:
            arr=arr2object(arr)
        if arr is not None and arr.ndim==0: #scalar
            arr=arr.reshape(1)
        if arr is not None:
            tmpid=dtype2id.get(arr.dtype.type)
            if tmpid is None:
                raise TypeError(f'cell: unsupported data type {arr.dtype}. Supported are {[np.dtype(key).name for key in dtype2id]}')
            if tid!=0 and tmpid != tid and tid!=0x6421 : #and tmpid !=0x6421:
                dtp = next((key for key, value in dtype2id.items() if value == tid), None)
                if dtp is None:
                    raise TypeError(f'cell: cannot convert {arr.dtype} array to MAOS type {tid:#x} (sparse input is expected?)')
                try: #convert data
                    arr=arr.astype(dtp)
                    tmpid=tid
                except (TypeError, ValueError) as err:
                    raise TypeError(f'cell: data mismatch want {tid:#x}, got {tmpid:#x}: {err}') from err
            self.id=tmpid

            if arr.ndim>0:
                self.nx=arr.shape[-1]
            if arr.ndim>1:
                self.ny=arr.shape[-2]
            else:
                if self.nx>0:
                    self.ny=1
                else:
                    self.ny=0
            if self.nx==0:
                self.p=0
            elif arr.dtype.kind != 'O':
                if arr.flags['C']==False:
                    arr=arr.copy(order='C')
                self.p=arr.ctypes.data_as(c_void_p)
                header=getattr(arr, 'header', None)
                if isinstance(header, (np.ndarray, list)): #readbin gives an array of lines for multi-line header
                    header='\n'.join(str(line) for line in np.ravel(header))
                if isinstance(header, str):
                    self.header_bytes=header.encode("utf-8") #keep a reference
                    self.header=c_char_p(self.header_bytes)
            else:
                self.qarr=np.zeros(self.shape(1), dtype=object) #stores objects
                self.parr=np.zeros(self.shape(1), dtype=c_void_p) #store pointer of objects
                for iy in range(self.ny):
                    for ix in range(self.nx):
                        if arr.ndim==1:
                            arri=arr[ix]
                        else:
                            arri=arr[iy,ix]
                        if arri is not None:
                            self.qarr[iy,ix]=py2cell(arri) #object array
                        if self.qarr[iy,ix] is None or isinstance(self.qarr[iy,ix], int): #None or empty element
                            self.parr[iy,ix]=0
                        elif isinstance(self.qarr[iy,ix], Structure):
                            self.parr[iy,ix]=addressof(self.qarr[iy,ix]) #object pointer array
                        else:
                            raise TypeError(f'cell: element ({iy},{ix}) of type {type(arri)} cannot be converted')
                self.p=self.parr.ctypes.data_as(c_void_p)
            self.arr=arr #keep a reference to arr as it can be a copy otherwise it may be destroyed
        else:
            self.id=0x6421
            self.p=None
            self.nx=0
            self.ny=0

    def shape(self, force2d=0):
        '''Python shape of the C array: (ny, nx), or (nx,) if ny<=1 and not force2d.'''
        if self.ny > 1 or force2d:
            return (self.ny, self.nx)
        else:
            return (self.nx,) #last , is necessary

def simplify(arr, do_stack=1, do_squeeze=0):
    '''Convert object array a[i,j][k,n]... to simple ndarray a[i,j,k,n,...].

    Shape and singleton dimensions are preserved unless do_squeeze is set.
    Stacking is only done when all the non-empty elements have the same shape
    and every element is non-empty; otherwise the (simplified) object array is
    returned.

    Args:
        arr: numpy (object) array or list.
        do_stack: stack the elements into a numeric array when possible.
        do_squeeze: remove singleton dimensions; a single element is returned as a scalar.

    Returns:
        numpy array, or a scalar when do_squeeze is set and there is one element.
    '''
    if type(arr) is list:
        if len(arr)==1:
            arr=arr[0]
        else:
            arr=np.array(arr)
    if type(arr) is np.ndarray and do_squeeze:
        arr=np.squeeze(arr)
        if arr.size==1:
            return arr.item(0) #this works for 0d array
    if type(arr) is np.ndarray and arr.dtype.name=='object':
        flags=np.zeros(arr.shape,dtype=bool)
        can_stack=0
        for ind,iarr in np.ndenumerate(arr):
            arr[ind]=simplify(iarr,do_stack,do_squeeze)
            if getattr(arr[ind], 'size', 0)>0: #None or scalar elements have no size
                flags[ind]=True
                if getattr(arr[ind], 'dtype', None) is not None and arr[ind].dtype.name!='object':
                    can_stack=1
                    shape=arr.shape+arr[ind].shape
        if do_stack and can_stack:
            try:
                arr2=np.stack(arr[flags])
                arr2.shape=shape #fails if some elements are empty
                if do_squeeze:
                    arr2=np.squeeze(arr2)
                arr=arr2 #only replace arr when stacking succeeded
            except (ValueError, TypeError) as err: #shapes differ or some elements are empty: keep object array
                #print('stack failed', err)
                pass
    return arr


"""ctypes interface between Python (numpy/scipy) and the MAOS C library aolib.so.

This module loads aolib.so (built in the bin folder of a MAOS build directory)
and converts between numpy/scipy objects and the MAOS C types:
    - dense numpy arrays <-> dmat/smat/cmat/zmat/lmat (math/type.h)
    - numpy object arrays <-> cell arrays (nested)
    - scipy sparse arrays <-> dsp/ssp/csp/zsp (MAOS CSC; see csr below)
    - numpy arrays of shape (2, n) -> loc_t (lib/loc.h)
    - dict <-> C structs (make_class, dict_to_struct)
The wrapper functions in libaos.py (generated by lib2py.py) do
``from interface import *`` and use py2cell/py2cellref for inputs and ct2py
for outputs. MAOS arrays are column major, so an array of nx*ny in C has shape
(ny, nx) in Python (a vector with ny==1 has shape (nx,)).

Usage:
    export MAOS_AOLIB=/path/to/maos/build/bin/aolib.so
    import libaos
    res=libaos.read('Res_1.bin')

Requirements: numpy, scipy, and aolib.so from a MAOS build. The library path is
taken from the environment variable MAOS_AOLIB (default: aolib.so in the
dynamic library search path). The interface assumes the default double
precision build (real is double) with 64 bit sparse index (DLONG).

Raises:
    OSError: at import if aolib.so cannot be loaded.
"""

def py2cell(arr, tid=0):
    '''Convert numpy array to C array adaptively (based on its type).

    Args:
        arr: numpy array (numeric or object array for cells), list, scalar,
            scipy sparse array, or None. Other objects (e.g., ctypes
            pointers used for output arguments) are returned unchanged.
        tid: expected MAOS type id (e.g., 0x6402 for dmat, 0x6421 for any
            cell; 0 for any). Dense data is converted to it if needed.

    Returns:
        cell or csr object (borrowing the numpy memory; keep arr alive while it
        is used), None for None or empty arrays, or arr unchanged.

    Raises:
        TypeError: if the data type cannot be converted.
    '''
    if arr is None:
        return None
    if type(arr) is list:
        arr=np.asarray(arr)
    elif isinstance(arr, (int, float, complex, np.number)) and not isinstance(arr, bool):
        arr=np.asarray(arr).reshape(1) #scalar as a vector of 1 element
    if sp.issparse(arr):
        arr=csr(arr, tid)
    elif isinstance(arr, np.ndarray):
        if arr.size==0:
            arr=None
        else:
            arr=cell(arr, tid)
    return arr

def py2cellref(arr, tid=0):
    '''Convert numpy array to a reference (pointer) to C array, see py2cell.

    Returns None (NULL pointer) if arr is None or empty. Used for both input
    and output arguments (arr is a ctypes POINTER(cell)() for output).
    '''
    arr=py2cell(arr, tid)
    if arr is None:
        return None
    else:
        return byref(arr)

def arr2object(arr): 
    '''Convert numpy number arrays with more than 2 dimensions to numpy object arrays.

    The leading 1 (odd ndim) or 2 (even ndim) dimensions become the object
    array, recursively, until each element has at most 2 dimensions. E.g., an
    array of shape (3,4,5) becomes an object array of shape (3,) with elements
    of shape (4,5). Non-ndarray input is returned unchanged with a message.
    '''
    if not isinstance(arr, np.ndarray):
        print('Unsupported data type')
        return arr
    if arr.ndim<=2:
        return arr
    ndim=2-(arr.ndim%2)
    arr2=np.empty((arr.shape[0:ndim]),dtype=object)
    if ndim==2:
        for i in range(arr2.shape[0]):
            for j in range(arr2.shape[1]):
                arr2[i,j]=arr2object(arr[i,j])
    else:
        for i in range(arr2.shape[0]):
            arr2[i]=arr2object(arr[i])
    return arr2


